export type TranslationKey = keyof typeof translations.en;

const FALLBACK: LanguageCode = "en";

export function t(lang: LanguageCode, key: string): string {
  const dict = translations[lang] ?? translations[FALLBACK];
  const value = dict[key];
  if (value !== undefined) return value;
  const fallbackVal = translations[FALLBACK][key];
  return fallbackVal !== undefined ? fallbackVal : key;
}

export function getLanguageDir(lang: LanguageCode): "ltr" | "rtl" {
  return SUPPORTED_LANGUAGES.find((l) => l.code === lang)?.dir ?? "ltr";
}
